// Appended to app.js only in a disposable integration-test copy.
import { applyPower, sweepBox } from './game.js';
import { fs, getenv } from '@sys';
async function runChecks() {
  const results = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); results.push(label); };
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const fresh = () => { const value = createGame(7); start(value); launch(value); return value; };
  const brick = (hp = 1) => ({ id: 1, x: 450, y: 150, w: 60, h: 24, hp, maxHp: hp, color: '#67e8f9', power: null });
  const shoot = (value, hp = 1) => {
    value.bricks = [brick(hp)]; value.balls = [{ x: 480, y: 182, vx: 0, vy: -600, r: 7, trail: [] }];
  };
  const key = (type, value) => document.dispatchEvent(new KeyboardEvent(type, { key: value, bubbles: true, cancelable: true }));
  try {
    assert(game.phase === 'title' && $('overlay').textContent.includes('Start a run'), 'Title screen and initial playfield render');
    const a = createGame(7); assert(!launch(a), 'A title screen cannot launch a ball before starting');
    start(a); assert(a.phase === 'ready' && a.lives === 3 && a.balls.length === 1, 'A new run starts with three lives and a docked ball');
    launch(a); assert(a.phase === 'playing' && a.balls[0].vy < 0, 'Launch gives the ball an upward velocity');
    for (let i = 0; i < 240; i++) update(a, STEP, { direction: -1 });
    assert(a.paddle.x >= 14 + a.paddle.w / 2, 'Keyboard steering clamps the paddle inside the arena');
    const wall = fresh(); Object.assign(wall.balls[0], { x: WIDTH - 22, y: 400, vx: 500, vy: -100 }); update(wall, STEP);
    assert(wall.balls[0].vx < 0 && wall.balls[0].x <= WIDTH - 21, 'Wall contact reflects the ball without escaping the boundary');
    const paddle = fresh(); Object.assign(paddle.balls[0], { x: paddle.paddle.x + 30, y: paddle.paddle.y - 8, vx: 0, vy: 480 }); paddle.combo = 4; update(paddle, STEP);
    assert(paddle.balls[0].vy < 0 && paddle.balls[0].vx > 0 && paddle.combo === 0, 'Paddle offset changes the return angle and resets the combo');
    const sweep = sweepBox({ x: 480, y: 300, vx: 0, vy: -30000, r: 7 }, brick(), STEP);
    assert(sweep && sweep.t < STEP && sweep.ny === 1, 'Swept collision finds a brick crossed within one physics step');
    const fast = fresh(); shoot(fast); fast.bricks.push({ ...brick(), id: 2, x: 100 }); Object.assign(fast.balls[0], { y: 300, vy: -30000 }); update(fast, STEP);
    assert(fast.bricks[0].hp === 0 && fast.balls[0].vy > 0 && fast.score > 0, 'A fast ball cannot tunnel through a brick');
    const armor = fresh(); shoot(armor, 2); update(armor, STEP);
    assert(armor.bricks[0].hp === 1 && armor.phase === 'playing' && armor.score === 10, 'Armored bricks survive the first hit');
    Object.assign(armor.balls[0], { x: 480, y: 182, vx: 0, vy: -600 }); update(armor, STEP);
    assert(armor.bricks[0].hp === 0 && armor.phase === 'clear', 'The second armor hit clears the sector');
    const powers = fresh(); applyPower(powers, 'wide');
    assert(powers.paddle.w === 174 && powers.wideUntil > powers.time, 'Wide paddle power-up starts its duration');
    powers.time = powers.wideUntil; update(powers, STEP);
    assert(powers.paddle.w === 112 && powers.wideUntil === 0, 'Wide paddle expires on simulation time');
    applyPower(powers, 'multi'); applyPower(powers, 'multi');
    assert(powers.balls.length === 3, 'Multiball is bounded to three balls');
    powers.balls[0].y = HEIGHT + 40; update(powers, STEP);
    assert(powers.balls.length === 2 && powers.lives === 3, 'Losing one multiball does not consume a life');
    const shield = fresh(); applyPower(shield, 'shield'); Object.assign(shield.balls[0], { x: 100, y: HEIGHT - 31, vx: 0, vy: 450 }); update(shield, STEP);
    assert(shield.shield === 0 && shield.balls[0].vy < 0 && shield.lives === 3, 'A safety shield saves one ball and is consumed');
    const drop = fresh(); drop.drops = [{ x: drop.paddle.x, y: drop.paddle.y - 11, kind: 'wide' }]; update(drop, STEP);
    assert(drop.drops.length === 0 && drop.paddle.w === 174, 'Catching a falling capsule applies its power-up');
    const frozen = fresh(); pause(frozen); const frozenX = frozen.balls[0].x, frozenTime = frozen.time; update(frozen, STEP, { direction: 1 });
    assert(frozen.balls[0].x === frozenX && frozen.time === frozenTime && frozen.phase === 'paused', 'Paused physics and power-up time remain frozen');
    resume(frozen); assert(frozen.phase === 'playing', 'Resume restores the active run');
    assert(nextLevel(armor) && armor.level === 1 && armor.bricks.some(row => row.hp === 2), 'Sector progression loads the next armored layout');
    const win = fresh(); win.level = LEVELS - 1; shoot(win); update(win, STEP);
    assert(win.phase === 'won' && drainEvents(win).some(event => event.kind === 'victory'), 'Clearing the final sector produces a victory');
    const loss = fresh();
    for (let i = 0; i < 3; i++) { if (loss.phase === 'ready') launch(loss); for (const ball of loss.balls) ball.y = HEIGHT + 40; update(loss, STEP); }
    assert(loss.phase === 'over' && loss.lives === 0, 'Losing the last ball three times ends the run');
    update(loss, STEP); assert(loss.lives === 0, 'Game-over state cannot consume additional lives');
    const first = fresh(), second = fresh();
    for (let i = 0; i < 120; i++) { const input = { direction: i < 60 ? -1 : 1 }; update(first, STEP, input); update(second, STEP, input); }
    assert(first.balls[0].x === second.balls[0].x && first.score === second.score && first.phase === second.phase, 'Identical seeds and fixed inputs produce identical simulation');
    assert(sound.voiceCount() === 13 && sound.music.loop, 'Audio uses a bounded pool and looping music');
    const clip = new Audio('sounds/brick.wav'); clip.load();
    assert(clip.duration > .08 && clip.duration < .2 && !clip.error, 'Bundled WAV effects load through the real audio API');
    const other = new Audio('sounds/paddle.wav'); await Promise.all([clip.play(), other.play()]);
    assert(!clip.paused && !other.paused, 'Separate sound effects can overlap'); clip.pause(); other.pause();
    $('overlay').querySelector('[data-game-action="primary"]').click(); await sleep(100);
    assert(game.phase === 'playing' && simulationSteps > 0 && frames > 0, 'Start button runs the real animation and fixed-step simulation');
    assert(!sound.music.paused, 'Starting a run plays the background loop');
    const paddleBefore = game.paddle.x; key('keydown', 'ArrowLeft'); await sleep(80); key('keyup', 'ArrowLeft');
    assert(game.paddle.x < paddleBefore, 'Held keyboard input steers continuously');
    key('keydown', 'a'); key('keydown', 'ArrowLeft'); key('keyup', 'a');
    assert(keys.has('arrowleft'), 'Releasing one steering alias leaves the other held key active'); key('keyup', 'ArrowLeft');
    const box = canvas.getBoundingClientRect(); const beforeMouse = game.paddle.x;
    canvas.dispatchEvent(new MouseEvent('mousemove', { clientX: box.x + box.width * .85, clientY: box.y + 200, bubbles: true })); await sleep(80);
    assert(input.target > WIDTH * .8 && game.paddle.x > beforeMouse, 'Mouse steering maps CSS coordinates into the logical playfield');
    key('keydown', 'p'); const pausedTime = game.time; key('keydown', 'p'); await sleep(100);
    assert(game.phase === 'paused' && game.time === pausedTime && sound.music.paused, 'Pause freezes physics and music; key repeat cannot toggle it back'); key('keyup', 'p');
    key('keydown', 'p'); key('keyup', 'p'); assert(game.phase === 'playing', 'A fresh pause-key press resumes the run');
    key('keydown', 'ArrowRight'); window.dispatchEvent(new Event('blur'));
    assert(game.phase === 'paused' && keys.size === 0, 'Losing focus pauses and clears held controls');
    primary(); __windowActivate(0);
    assert(game.phase === 'paused', 'Native window deactivation also pauses the run'); __windowActivate(1);
    assert(game.phase === 'paused', 'Window activation never resumes gameplay automatically');
    $('settings').click();
    assert(panel === 'settings' && $('volume'), 'Settings open while the simulation remains paused');
    $('volume').value = '.3'; $('volume').dispatchEvent(new Event('input', { bubbles: true }));
    $('music').checked = false; $('music').dispatchEvent(new Event('change', { bubbles: true }));
    $('reduced').checked = true; $('reduced').dispatchEvent(new Event('change', { bubbles: true }));
    $('sharp').checked = true; $('sharp').dispatchEvent(new Event('change', { bubbles: true }));
    assert(preferences.volume === .3 && !preferences.music && preferences.reduced && canvas.width === 1440, 'Settings control audio, reduced motion, and canvas resolution');
    $('overlay').querySelector('[data-game-action="back"]').click();
    assert(game.phase === 'paused' && !panel, 'Leaving settings preserves the paused run');
    renderer.events(Array.from({ length: 100 }, () => ({ kind: 'brick', broken: true, x: 10, y: 10, color: '#fff' })));
    assert(renderer.particleCount() === 0, 'Reduced-motion mode suppresses particles');
    preferences.reduced = false; configure();
    renderer.events(Array.from({ length: 100 }, () => ({ kind: 'brick', broken: true, x: 10, y: 10, color: '#fff' })));
    assert(renderer.particleCount() <= 140, 'Particle effects remain bounded under a burst of collisions'); renderer.clear();
    game.phase = 'clear'; game.level = 0; sync(); $('overlay').querySelector('[data-game-action="primary"]').click();
    assert(game.level === 1 && game.phase === 'playing', 'Sector-clear button advances the playable run');
    game.phase = 'won'; game.level = 2; game.score = 4321; sync(); $('overlay').querySelector('[data-game-action="primary"]').click();
    assert(game.phase === 'playing' && game.level === 0 && game.score === 0 && best === 4321, 'Victory offers a fresh run and preserves its high score');
    key('keydown', 'm'); const mutedOnce = preferences.muted; key('keydown', 'm'); key('keyup', 'm');
    assert(preferences.muted === mutedOnce, 'Mute is edge-triggered rather than repeated while a key is held');
    preferences.muted = true; preferences.music = false; preferences.volume = .3; preferences.sharp = false; preferences.reduced = true; configure(); persist();
    const saved = JSON.parse(localStorage.getItem(storageKey));
    assert(saved.best === 4321 && saved.muted && saved.volume === .3, 'High score and sound preferences save to local storage');
    pause(game); sync(); stopped = true; cancelAnimationFrame(rafId); sound.stop();
    fs.writeFileSync(getenv('NEON_TEST_REPORT'), JSON.stringify({ ok: true, results, best, frames, simulationSteps }));
    console.log('NEON CHECKS PASSED: ' + results.length);
  } catch (error) {
    stopped = true; cancelAnimationFrame(rafId); sound.stop();
    fs.writeFileSync(getenv('NEON_TEST_REPORT'), JSON.stringify({ ok: false, results, error: error.message, stack: error.stack }));
    console.error('NEON CHECKS FAILED: ' + error.stack);
  }
}
runChecks();
